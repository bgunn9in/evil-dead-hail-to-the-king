"""Generate the small host UI byte table; no runtime JSON or UTF-8 parser."""
import argparse
import json
from pathlib import Path

from compile_localization import font_charset


def unique(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("Duplicate UI key")
        result[key] = value
    return result


def generate(source, font, output):
    document = json.loads(Path(source).read_text(encoding="utf-8"), object_pairs_hook=unique)
    if document.get("format") != "ED-HOST-UI-RU1" or not document.get("entries"):
        raise ValueError("Unsupported host UI catalog")
    charset = font_charset(font)
    entries = []
    for key, value in sorted(document["entries"].items()):
        key.encode("ascii", errors="strict")
        raw = value.encode("cp1251", errors="strict")
        if not key or "\0" in key or not raw or b"\0" in raw or len(raw) > 512 or any(c != 32 and c not in charset for c in raw):
            raise ValueError("UI label is empty, over512bytes or lacks a declared font glyph: " + key)
        encoded = "".join("\\%03o" % c for c in raw)
        entries.append("    {%s,\"%s\"}," % (json.dumps(key, ensure_ascii=True), encoded))
    result = """// Generated by tools/compile_ui_localization.py from localization/ui-ru.json; CP1251.
#pragma once
#include <algorithm>
#include <iterator>
#include <string>
#include <string_view>
namespace edui {
struct Entry {std::string_view english,russian;};
inline constexpr Entry entries[]={
""" + "\n".join(entries) + """
};
inline std::string text(std::string_view english,bool russian=false) {
    if(russian){const auto found=std::lower_bound(std::begin(entries),std::end(entries),english,
        [](const Entry& entry,std::string_view key){return entry.english<key;});
        if(found!=std::end(entries)&&found->english==english)return std::string(found->russian);}
    return std::string(english);
}
}
"""
    Path(output).write_text(result, encoding="ascii", newline="\n")
    return len(entries)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("source", "font", "output"):
        parser.add_argument("--" + name, type=Path, required=True)
    args = parser.parse_args()
    print("Generated", generate(args.source, args.font, args.output), "checked host UI labels")
